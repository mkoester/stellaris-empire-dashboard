#!/usr/bin/env node
// Writes the companion mod's tech-options event (mod/dashboard_feed/events/sdash_tech_options.txt)
// from the extraction's data DB. The game has no way to list the research options in script, only
// `has_tech_option = <key>` (4.5.4 triggers.log, country scope), so the event asks it once per tech
// and logs each one on offer. The keys are spelled out: a parameter inside a quoted log string came
// out one character off in 4.5.2 (sdash_events.txt). Re-run after a game update and commit the
// result with the mod.
//
//   node scripts/gen-tech-options.mjs --db <data DB> --out mod/dashboard_feed/events/sdash_tech_options.txt
import { writeFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { parseArgs } from 'node:util';

const { values } = parseArgs({
	options: { db: { type: 'string' }, out: { type: 'string' } }
});
if (!values.db || !values.out) {
	console.error('usage: gen-tech-options.mjs --db <data DB> --out <events file>');
	process.exit(2);
}

const db = new DatabaseSync(values.db, { readOnly: true });
const version = db.prepare(`SELECT value FROM meta WHERE key = 'game_version'`).get()?.value;
// start techs (cost 0) are researched from the start, never an option
const techs = db
	.prepare(`SELECT key FROM technology WHERE cost IS NULL OR cost > 0 ORDER BY area, key`)
	.all()
	.map((r) => String(r.key));
db.close();

const line = (rest) => `"SDASH|3|[GetDate]|[This.sdash_run]|event|${rest}"`;
const out = `# Generated by scripts/gen-tech-options.mjs from the data DB of ${version ?? 'an unknown game version'} — do not edit.
namespace = sdash

# 0.13.0: the research options on offer, the day after the month starts and the day after a tech
# is researched — when its field draws new cards (sdash_queue_tech_options schedules it): one
# line per tech on offer, then an end line, so the dashboard tells an empty list from a lost one.
# Event lines, so an older dashboard skips them; with the run id, so a replayed day is not dropped
# as a repeat (sdash_events.txt). Parsed by src/lib/server/feed.ts. ${techs.length} techs.
country_event = {
	id = sdash.6
	hide_window = yes
	is_triggered_only = yes

	trigger = {
		is_ai = no
	}

	immediate = {
${techs.map((t) => `\t\tif = { limit = { has_tech_option = ${t} } log = ${line(`tech-option|${t}`)} }`).join('\n')}
		log = ${line('tech-options-end')}
	}
}
`;
writeFileSync(values.out, out);
console.log(`${values.out}: ${techs.length} techs`);
